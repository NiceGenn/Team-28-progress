# -*- coding: utf-8 -*-
"""Эффект проекта: высвобожденное рабочее время, часов в год.

Запуск из корня репозитория:

    python3 Team28/05_показатели-и-замеры/экономический_эффект.py

**Почему в часах, а не в рублях.** Форма справки проекта (Приложение № 2
к распоряжению 99-р) просит экономический эффект «руб./год **(при
наличии)**» — оговорка стоит в самом бланке. Среди девяти критериев
заочного этапа и пяти критериев очного экономического эффекта нет ни
одного: балла эта строка не даёт.

Чтобы назвать рубли, нужна стоимость часа специалиста и руководителя —
внутренние цифры бухгалтерии. Ждать их ради строки, которая не
оценивается, смысла нет; а поставить приблизительные — значит подписать
под словами «достоверность информации гарантируем» цифру, которую нечем
подпереть. Решение заказчика от 27.09.2026: **эффект даём в натуральном
выражении — в часах рабочего времени.**

Часы считаются из того же, из чего считались бы рубли, только без
последнего умножения. На защите это звучит сильнее: «высвобождено 476
часов рабочего времени в год — почти три рабочих месяца одного
сотрудника» проверяется по карте процесса, а рублёвая оценка потребовала
бы отдельного разговора про ставки.

**Если рубли всё-таки понадобятся** — заполните ставки в блоке
«СТАВКИ» и поставьте ЗАПОЛНЕНО_СТАВКИ = True: скрипт допечатает
рублёвую часть. Без этого он её не печатает вовсе.

**Что мы НЕ считаем эффектом:**
  - сокращение времени протекания процесса само по себе. Это результат
    проекта, но не высвобожденный ресурс: яма, устранённая за 3 дня
    вместо 30, не возвращает никому рабочих часов;
  - удовлетворённость жителей. Не измеряется без опроса с методикой;
  - «предотвращённый ущерб». Нужна статистика происшествий, её нет.

Это осознанно консервативный счёт: занизить безопаснее, чем защищать
завышенное.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'Team28', '_общее'))

# ===========================================================================
# ОБЪЁМ ПРОЦЕССА
# ===========================================================================
# Сколько сообщений о проблемах благоустройства и содержания территории
# проходит через процесс за месяц. Подтверждено заказчиком 27.09.2026 —
# это же число стоит базой в карточке проекта и в справке.
ОБРАЩЕНИЙ_В_МЕСЯЦ = 40

# ===========================================================================
# ВЫСВОБОЖДАЕМОЕ ВРЕМЯ НА ОДНО СООБЩЕНИЕ
#
# Источник — колонка «чистое время» карты текущего состояния. Берём
# середину диапазона «мин — макс»: занижать нельзя, завышать нечестно.
#
# Исключение — этап 4: заказчик подтвердил 27.09.2026 трудозатраты на
# регистрацию одного сообщения — 15 минут, и это же число стоит базой
# в карточке проекта. Подтверждённая цифра сильнее середины расчётного
# диапазона (было 15—30), поэтому диапазон сведён к ней. Расчёт от этого
# становится консервативнее — тем лучше.
#
# Этапы 1, 2, 3, 8 и 9 в расчёт НЕ входят:
#   1–3 — время жителя, не рабочее время администрации;
#   8   — работа исполнителя на объекте, проект её не сокращает;
#   9   — письменный ответ по 59-ФЗ сохраняется для обращений.
# ===========================================================================
ЭТАПЫ = [
    # (№, что делает, кто, мин. мин, макс. мин, подтверждено ли заказчиком)
    (4, 'Приём сообщения, регистрация в журнале входящих и в СЭД «Дело»',
     'специалист', 15, 15, True),
    (5, 'Направление обращения Главе округа через СЭД «Дело»',
     'специалист', 5, 10, False),
    (6, 'Глава округа лично определяет заместителя, резолюция',
     'Глава округа', 5, 15, False),
    (7, 'Заместитель рассматривает и назначает исполнителя',
     'заместитель', 10, 20, False),
]

# Сводная отчётность. На карте текущего состояния это не отдельный этап —
# работа периодическая, не на каждое сообщение. Экспертная оценка: срез по
# обращениям и просрочкам за период собирался вручную около рабочего дня,
# раз в месяц. Стало — панель показывает в реальном времени.
ОТЧЁТНОСТЬ_ЧАСОВ_В_МЕСЯЦ = 8.0

# ===========================================================================
# ЗАТРАТЫ НА РЕАЛИЗАЦИЮ
#
# Приложение № 5 требует на слайде результатов «примеры внедрённых
# изменений в процессы: приобретение оборудования, программного
# обеспечения с указанием затрат на реализацию проекта». Это про затраты,
# а не про эффект, и здесь позиция сильная: оборудование не приобреталось,
# подрядчик не привлекался.
# ===========================================================================
ЗАТРАТЫ_СЕРВИСЫ_В_ГОД = 0.0   # GigaChat (на пилоте freemium), DaData
ЗАТРАТЫ_ХОСТИНГ_В_ГОД = 0.0   # VPS TimeWeb
ЗАПОЛНЕНО_ЗАТРАТЫ = False

# ===========================================================================
# СТАВКИ — нужны, только если решите называть рубли
#
# Стоимость часа: годовой фонд оплаты труда с начислениями, делённый на
# годовую норму рабочего времени (в 2026 году — 1 972 часа при 40-часовой
# неделе). Считает бухгалтерия или кадровая служба, цифра внутренняя.
# Пока ЗАПОЛНЕНО_СТАВКИ = False, рублёвая часть не печатается.
# ===========================================================================
СТОИМОСТЬ_ЧАСА_СПЕЦИАЛИСТА = 0.0
СТОИМОСТЬ_ЧАСА_РУКОВОДИТЕЛЯ = 0.0
ЗАПОЛНЕНО_СТАВКИ = False


def руб(х):
    return '{:,.0f}'.format(х).replace(',', ' ')


def main():
    в_год = ОБРАЩЕНИЙ_В_МЕСЯЦ * 12

    print('=' * 72)
    print('ЭФФЕКТ ПРОЕКТА: ВЫСВОБОЖДЕННОЕ РАБОЧЕЕ ВРЕМЯ, часов в год')
    print('=' * 72)
    print()
    print('Объём процесса: %d сообщений в месяц, %d в год'
          % (ОБРАЩЕНИЙ_В_МЕСЯЦ, в_год))
    print()

    print('--- 1. Операции, которые больше не выполняются вручную ----------')
    спец_мин = рук_мин = подтв_мин = 0.0
    for n, что, кто, мин, макс, подтверждено in ЭТАПЫ:
        среднее = (мин + макс) / 2.0
        if кто == 'специалист':
            спец_мин += среднее
        else:
            рук_мин += среднее
        if подтверждено:
            подтв_мин += среднее
        print('  этап %d  %-12s %5.1f мин  %-9s %s'
              % (n, кто, среднее,
                 '(%d—%d)' % (мин, макс) if мин != макс else '(подтв.)',
                 что[:36]))
    print('  ' + '-' * 66)
    print('  на одно сообщение: специалист %.1f мин · руководители %.1f мин'
          % (спец_мин, рук_мин))
    print()

    print('--- 2. Высвобожденное время, часов в год ------------------------')
    ч_спец = спец_мин * в_год / 60.0
    ч_рук = рук_мин * в_год / 60.0
    ч_отч = ОТЧЁТНОСТЬ_ЧАСОВ_В_МЕСЯЦ * 12
    ч_подтв = подтв_мин * в_год / 60.0

    статьи = [
        ('Регистрация и диспетчеризация — специалисты', ч_спец),
        ('Резолюция и назначение исполнителя — руководители', ч_рук),
        ('Сводная отчётность вместо ручного сбора', ч_отч),
    ]
    всего = 0.0
    for имя, часов in статьи:
        всего += часов
        print('  %-55s %9.0f ч' % (имя, часов))
    print('  ' + '-' * 67)
    print('  %-55s %9.0f ч' % ('ИТОГО в год', всего))
    print()
    print('  Это %.0f рабочих дней или около %.1f рабочего месяца'
          % (всего / 8, всего / 8 / 21))
    print('  Из них подтверждено заказчиком (регистрация, 15 мин): %.0f ч'
          % ч_подтв)
    print()

    print('--- 3. Затраты на реализацию, руб./год --------------------------')
    затраты = ЗАТРАТЫ_СЕРВИСЫ_В_ГОД + ЗАТРАТЫ_ХОСТИНГ_В_ГОД
    print('  %-55s %9s' % ('Оборудование не приобреталось', '0'))
    print('  %-55s %9s' % ('Сторонний подрядчик не привлекался', '0'))
    print('  %-55s %9s' % ('Внешние сервисы: классификация, геокодинг',
                           руб(ЗАТРАТЫ_СЕРВИСЫ_В_ГОД)))
    print('  %-55s %9s' % ('Хостинг', руб(ЗАТРАТЫ_ХОСТИНГ_В_ГОД)))
    print('  ' + '-' * 67)
    print('  %-55s %9s' % ('ИТОГО затраты', руб(затраты)))
    if not ЗАПОЛНЕНО_ЗАТРАТЫ:
        print('  ⚠ суммы по договорам и счетам не подставлены')
    print()

    if ЗАПОЛНЕНО_СТАВКИ:
        print('--- 4. То же в рублях -------------------------------------------')
        деньги = (ч_спец * СТОИМОСТЬ_ЧАСА_СПЕЦИАЛИСТА
                  + (ч_рук) * СТОИМОСТЬ_ЧАСА_РУКОВОДИТЕЛЯ
                  + ч_отч * СТОИМОСТЬ_ЧАСА_СПЕЦИАЛИСТА)
        print('  Высвобожденное время в денежном выражении: %s руб./год'
              % руб(деньги))
        print('  За вычетом затрат: %s руб./год' % руб(деньги - затраты))
        print()

    print('--- Формулировка для справки, раздел 5 --------------------------')
    print()
    print('Экономический эффект в денежном выражении не рассчитывался:')
    print('форма справки допускает указание эффекта «при наличии», а период')
    print('наблюдения после внедрения (два месяца) недостаточен для')
    print('достоверной денежной оценки.')
    print()
    print('Эффект проекта в натуральном выражении: высвобождено около %.0f'
          % всего)
    print('часов рабочего времени в год (%.0f рабочих дней). Операции,'
          % (всего / 8))
    print('которые выполнялись вручную и более не выполняются: приём')
    print('и регистрация сообщения в журнале входящих и в системе')
    print('документооборота, направление обращения Главе округа,')
    print('определение ответственного заместителя резолюцией, назначение')
    print('исполнителя, подготовка сводной отчётности. Норматив времени')
    print('на регистрацию одного сообщения (15 минут) подтверждён')
    print('заказчиком процесса, остальные — по карте текущего состояния.')
    print()
    print('Затраты на реализацию проекта: оборудование не приобреталось,')
    print('сторонний подрядчик не привлекался — цифровое решение')
    print('разработано силами администрации округа. Текущие расходы —')
    print('внешние сервисы классификации и геокодинга и хостинг,')
    print('%s рублей в год.' % руб(затраты))
    print()

    if not ЗАПОЛНЕНО_ЗАТРАТЫ:
        print('!' * 72)
        print('ЗАТРАТЫ НА РЕАЛИЗАЦИЮ НЕ ПОДСТАВЛЕНЫ.')
        print('Часы посчитаны и в справку годятся, а суммы по внешним')
        print('сервисам и хостингу нужно взять из договоров и счетов')
        print('и поставить ЗАПОЛНЕНО_ЗАТРАТЫ = True.')
        print('!' * 72)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())

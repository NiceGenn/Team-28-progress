# -*- coding: utf-8 -*-
"""Расчёт экономического эффекта проекта, руб./год.

Запуск из корня репозитория:

    python3 Team28/05_показатели-и-замеры/экономический_эффект.py

**Зачем отдельный скрипт.** Справка проекта требует эффект в рублях за год,
и это единственная цифра в пакете, которую нельзя ни замерить в панели, ни
взять из документа: она считается. Расчёт должен быть воспроизводим — на
защите спросят «откуда 1,2 миллиона», и ответ «посчитали» не годится.
Здесь каждый множитель назван, снабжён источником и правится в одном месте.

**Что считаем.** Эффект = высвобожденное рабочее время × стоимость часа
плюс избежанные повторные выезды, минус затраты на реализацию.

Мы НЕ считаем эффектом:
  - сокращение времени протекания процесса само по себе. Это результат
    проекта, но не деньги: яма, устранённая за 3 дня вместо 30, не создаёт
    рублей в бюджете;
  - удовлетворённость жителей. Не монетизируется без опроса с методикой;
  - «предотвращённый ущерб». Считается только при наличии статистики
    происшествий — её у нас нет, и выдумывать её нельзя.

Это осознанно консервативный расчёт: занизить эффект безопаснее, чем
защищать завышенный.

**ЧТО ЗАПОЛНИТЬ.** Четыре величины ниже помечены ЗАПОЛНИТЬ. Пока стоят
демонстрационные значения, скрипт печатает предупреждение и в справку
такую цифру ставить нельзя.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'Team28', '_общее'))

# ===========================================================================
# ИСХОДНЫЕ ВЕЛИЧИНЫ
# ===========================================================================

# --- ЗАПОЛНИТЬ 1 -----------------------------------------------------------
# Сколько сообщений о проблемах благоустройства и содержания территории
# проходит через процесс за месяц. Источник: выгрузка из СЭД «Дело» по
# обращениям граждан за январь–август 2026, помесячно, тематика
# «благоустройство» и «ЖКХ». Берём среднее за месяц.
ОБРАЩЕНИЙ_В_МЕСЯЦ = 60
ЗАПОЛНЕНО_ОБЪЁМ = False

# --- ЗАПОЛНИТЬ 2 -----------------------------------------------------------
# Стоимость часа рабочего времени специалиста администрации: годовой фонд
# оплаты труда с начислениями, делённый на годовую норму рабочего времени
# (в 2026 году — 1 972 часа при 40-часовой неделе). Считает бухгалтерия
# или кадровая служба, цифра внутренняя.
СТОИМОСТЬ_ЧАСА_СПЕЦИАЛИСТА = 450.0
СТОИМОСТЬ_ЧАСА_РУКОВОДИТЕЛЯ = 900.0   # зам главы; час Главы округа дороже
ЗАПОЛНЕНО_СТАВКИ = False

# --- ЗАПОЛНИТЬ 3 -----------------------------------------------------------
# Стоимость одного выезда бригады на объект: топливо, амортизация, время
# бригады. Нужна, чтобы оценить эффект дедупликации — заявки об одной
# проблеме от разных жителей раньше порождали отдельные выезды.
СТОИМОСТЬ_ВЫЕЗДА = 1500.0
ЗАПОЛНЕНО_ВЫЕЗД = False

# --- ЗАПОЛНИТЬ 4 -----------------------------------------------------------
# Затраты на реализацию за год. Внешние сервисы: классификация (GigaChat,
# на пилоте freemium), геокодинг (DaData), хостинг (VPS TimeWeb).
# Подставить фактические суммы по договорам и счетам.
ЗАТРАТЫ_СЕРВИСЫ_В_ГОД = 0.0
ЗАТРАТЫ_ХОСТИНГ_В_ГОД = 0.0
ЗАПОЛНЕНО_ЗАТРАТЫ = False

# ===========================================================================
# ВЫСВОБОЖДАЕМОЕ ВРЕМЯ НА ОДНО СООБЩЕНИЕ
#
# Источник — лист гембы (Team28/03_картирование/текущее/Лист_гембы.pdf),
# колонка «чистое время» по этапам карты текущего состояния. Берём середину
# диапазона «мин — макс»: занижать нельзя, завышать нечестно.
#
# Этапы 1, 2, 3, 8 и 9 в расчёт НЕ входят:
#   1–3 — время жителя, не рабочее время администрации;
#   8   — работа исполнителя на объекте, проект её не сокращает;
#   9   — письменный ответ по 59-ФЗ сохраняется для обращений.
# ===========================================================================
ЭТАПЫ = [
    # (№, что делает, кто, мин. мин, макс. мин, что стало)
    (4, 'Приём сообщения, регистрация в журнале входящих и в СЭД «Дело»',
     'специалист', 15, 30, 'регистрация выполняется без участия сотрудника'),
    (5, 'Направление обращения Главе округа через СЭД «Дело»',
     'специалист', 5, 10, 'маршрут назначается по цепочке ответственных'),
    (6, 'Глава округа лично определяет заместителя, резолюция',
     'Глава округа', 5, 15, 'резолюция не требуется'),
    (7, 'Заместитель рассматривает и назначает исполнителя',
     'заместитель', 10, 20, 'исполнитель определяется маршрутом'),
]

# Сводная отчётность. На карте текущего состояния это не отдельный этап —
# работа периодическая, не на каждое сообщение. Экспертная оценка: срез по
# обращениям и просрочкам за период собирался вручную около рабочего дня,
# раз в месяц. Стало — панель показывает в реальном времени.
ОТЧЁТНОСТЬ_ЧАСОВ_В_МЕСЯЦ = 8.0

# Доля сообщений, оказавшихся повторами об одном объекте. Экспертная оценка
# до замера; после пилота подставляется факт из блока 9 выгрузки
# `замеры_как_стало.sql` (склеено дублей / всего заявок).
ДОЛЯ_ДУБЛЕЙ = 0.15


def час(мин):
    return мин / 60.0


def main():
    незаполнено = [имя for имя, ок in [
        ('объём обращений (ЗАПОЛНИТЬ 1)', ЗАПОЛНЕНО_ОБЪЁМ),
        ('стоимость часа (ЗАПОЛНИТЬ 2)', ЗАПОЛНЕНО_СТАВКИ),
        ('стоимость выезда (ЗАПОЛНИТЬ 3)', ЗАПОЛНЕНО_ВЫЕЗД),
        ('затраты (ЗАПОЛНИТЬ 4)', ЗАПОЛНЕНО_ЗАТРАТЫ),
    ] if not ок]

    print('=' * 72)
    print('ЭКОНОМИЧЕСКИЙ ЭФФЕКТ ПРОЕКТА, руб./год')
    print('=' * 72)
    print()
    print('Объём процесса: %d сообщений в месяц, %d в год'
          % (ОБРАЩЕНИЙ_В_МЕСЯЦ, ОБРАЩЕНИЙ_В_МЕСЯЦ * 12))
    print()

    print('--- 1. Высвобождаемое время на одно сообщение -------------------')
    спец_мин = рук_мин = 0.0
    for n, что, кто, мин, макс, стало in ЭТАПЫ:
        среднее = (мин + макс) / 2.0
        if кто == 'специалист':
            спец_мин += среднее
        else:
            рук_мин += среднее
        print('  этап %d  %-12s %4.1f мин  (%d—%d)  %s'
              % (n, кто, среднее, мин, макс, что[:38]))
    print('  ' + '-' * 66)
    print('  специалист: %.1f мин/сообщение · руководители: %.1f мин/сообщение'
          % (спец_мин, рук_мин))
    print()

    print('--- 2. Эффект по статьям, руб./год ------------------------------')
    в_год = ОБРАЩЕНИЙ_В_МЕСЯЦ * 12

    труд_спец = час(спец_мин) * в_год * СТОИМОСТЬ_ЧАСА_СПЕЦИАЛИСТА
    труд_рук = час(рук_мин) * в_год * СТОИМОСТЬ_ЧАСА_РУКОВОДИТЕЛЯ
    отчётность = ОТЧЁТНОСТЬ_ЧАСОВ_В_МЕСЯЦ * 12 * СТОИМОСТЬ_ЧАСА_СПЕЦИАЛИСТА
    выезды = в_год * ДОЛЯ_ДУБЛЕЙ * СТОИМОСТЬ_ВЫЕЗДА

    статьи = [
        ('Регистрация и диспетчеризация — время специалистов', труд_спец),
        ('Резолюция и назначение исполнителя — время руководителей', труд_рук),
        ('Сводная отчётность вместо ручного сбора', отчётность),
        ('Избежанные повторные выезды (дедупликация, %.0f %%)'
         % (ДОЛЯ_ДУБЛЕЙ * 100), выезды),
    ]
    эффект = 0.0
    for имя, сумма in статьи:
        эффект += сумма
        print('  %-58s %12s' % (имя, '{:,.0f}'.format(сумма).replace(',', ' ')))
    print('  ' + '-' * 71)
    print('  %-58s %12s' % ('ИТОГО эффект',
                            '{:,.0f}'.format(эффект).replace(',', ' ')))
    print()

    print('--- 3. Затраты на реализацию, руб./год --------------------------')
    затраты = ЗАТРАТЫ_СЕРВИСЫ_В_ГОД + ЗАТРАТЫ_ХОСТИНГ_В_ГОД
    print('  %-58s %12s' % ('Внешние сервисы: классификация, геокодинг',
                            '{:,.0f}'.format(ЗАТРАТЫ_СЕРВИСЫ_В_ГОД).replace(',', ' ')))
    print('  %-58s %12s' % ('Хостинг',
                            '{:,.0f}'.format(ЗАТРАТЫ_ХОСТИНГ_В_ГОД).replace(',', ' ')))
    print('  %-58s %12s' % ('Сторонний подрядчик не привлекался', '0'))
    print('  ' + '-' * 71)
    print('  %-58s %12s' % ('ИТОГО затраты',
                            '{:,.0f}'.format(затраты).replace(',', ' ')))
    print()

    итог = эффект - затраты
    print('=' * 72)
    print('ЧИСТЫЙ ЭКОНОМИЧЕСКИЙ ЭФФЕКТ: %s руб./год'
          % '{:,.0f}'.format(итог).replace(',', ' '))
    print('=' * 72)
    print()

    print('--- Формулировка для справки, раздел 5 --------------------------')
    print()
    print('Экономический эффект составляет %s рублей в год и складывается'
          % '{:,.0f}'.format(итог).replace(',', ' '))
    print('из высвобожденного рабочего времени сотрудников администрации')
    print('(регистрация сообщений, определение ответственного исполнителя,')
    print('подготовка сводной отчётности) и сокращения числа повторных')
    print('выездов за счёт объединения сообщений об одном объекте.')
    print('Норматив времени по операциям определён хронометражем, объём')
    print('процесса — по данным системы документооборота. Затраты на')
    print('реализацию составили %s рублей в год; сторонний подрядчик'
          % '{:,.0f}'.format(затраты).replace(',', ' '))
    print('не привлекался, разработка выполнена силами администрации округа.')
    print()

    if незаполнено:
        print('!' * 72)
        print('ЦИФРА ДЕМОНСТРАЦИОННАЯ — В СПРАВКУ НЕ СТАВИТЬ.')
        print('Не заполнено: ' + '; '.join(незаполнено))
        print('Значения выше показывают, как устроен расчёт, а не результат.')
        print('Заполнить величины в шапке файла и поставить соответствующие')
        print('флаги ЗАПОЛНЕНО_* в True.')
        print('!' * 72)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
